const seen = new Set<string>();
for (const term of TERMS_RAW) {
  const key = term.trim().toLowerCase();
  if (seen.has(key)) throw new Error(`Повтор термина: ${term}`);
  seen.add(key);
}

if (TERMS_RAW.length < 150) {
  throw new Error(`Слишком мало терминов: ${TERMS_RAW.length}`);
}

export const TERMS: readonly string[] = TERMS_RAW;

function shuffle(list: readonly string[]): string[] {
  const copy = list.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const a = copy[i]!;
    const b = copy[j]!;
    copy[i] = b;
    copy[j] = a;
  }
  return copy;
}

export function createSequence(current: string | null): string[] {
  let target = TERMS[Math.floor(Math.random() * TERMS.length)]!;
  while (target === current) {
    target = TERMS[Math.floor(Math.random() * TERMS.length)]!;
  }

  const length = 34 + Math.floor(Math.random() * 7);
  const middleCount = length - (current ? 2 : 1);
  const pool = shuffle(TERMS.filter((term) => term !== target && term !== current));
  const middle: string[] = [];
  for (let i = 0; i < middleCount; i++) middle.push(pool[i % pool.length]!);
  return current ? [current, ...middle, target] : [...middle, target];
}
